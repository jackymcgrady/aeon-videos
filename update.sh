#!/usr/bin/env bash
# Re-fetch Aeon's official video sitemap and regenerate data.js.
# Usage: ./update.sh            (fetches https://assets.aeon.co/sitemaps/aeon/video.xml)
#        ./update.sh file.xml   (parses a local copy instead)
set -euo pipefail
cd "$(dirname "$0")"
URL="https://assets.aeon.co/sitemaps/aeon/video.xml"
TMP="$(mktemp)"; trap 'rm -f "$TMP"' EXIT
if [ $# -ge 1 ]; then cp "$1" "$TMP"; else curl -fsS --compressed -o "$TMP" "$URL"; fi
python3 -I - "$TMP" data.js <<'PY'
import sys, json, xml.etree.ElementTree as ET
from datetime import datetime
src, out = sys.argv[1], sys.argv[2]
NS = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9",
      "v": "http://www.google.com/schemas/sitemap-video/1.1"}
FIELDS = ["title", "description", "publication_date", "category", "duration",
          "thumbnail_loc", "player_loc", "uploader", "requires_subscription"]
rows, fails = [], []
for u in ET.parse(src).getroot().findall("s:url", NS):
    loc = (u.findtext("s:loc", "", NS) or "").strip()
    v = u.find("v:video", NS)
    if v is None:
        fails.append(loc); continue
    r = {"url": loc}
    for f in FIELDS:
        r[f] = (v.findtext("v:" + f, None, NS) or "").strip()
    try:
        r["duration"] = int(r["duration"])
        r["ts"] = int(datetime.fromisoformat(r["publication_date"].replace("Z", "+00:00")).timestamp())
    except ValueError:
        fails.append(loc); continue
    if not all([loc, r["title"], r["description"], r["category"], r["thumbnail_loc"], r["player_loc"]]):
        fails.append(loc); continue
    rows.append(r)
if fails:
    sys.exit("parse failures (%d): %s" % (len(fails), ", ".join(fails[:10])))
rows.sort(key=lambda r: (-r["ts"], r["title"], r["url"]))
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by update.sh from %s — do not edit by hand.\n" % "aeon.co video sitemap")
    fh.write("const VIDEOS = [\n")
    fh.write(",\n".join(json.dumps(r, ensure_ascii=False, sort_keys=False) for r in rows))
    fh.write("\n];\n")
print("data.js: %d videos, 0 parse failures" % len(rows))
PY
